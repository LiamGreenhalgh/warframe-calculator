export function getWeapon(id: string): WeaponBase | undefined {
  return WEAPONS.find((w) => w.id === id);
}

export function searchWeapons(q: string): WeaponBase[] {
  const n = q.trim().toLowerCase();
  if (!n) return WEAPONS;
  return WEAPONS.filter((w) => w.name.toLowerCase().includes(n) || w.id.includes(n) || w.slot.includes(n));
}
